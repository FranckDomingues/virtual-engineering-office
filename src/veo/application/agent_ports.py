"""Ports for local, human-supervised agent task orchestration."""
from pathlib import Path
from typing import Protocol

from veo.domain.agent_tasks import AgentTask, ExecutionRecord


class AgentTaskRepository(Protocol):
    def list_tasks(self) -> list[AgentTask]: ...
    def get_task(self, task_id: str) -> AgentTask | None: ...
    def save_task(self, task: AgentTask) -> None: ...
    def get_execution(self, task_id: str) -> ExecutionRecord | None: ...
    def save_execution(self, record: ExecutionRecord) -> None: ...


class PromptWriter(Protocol):
    def write_prompt(self, task: AgentTask, destination: Path) -> Path: ...


class Clock(Protocol):
    def now(self) -> str: ...
